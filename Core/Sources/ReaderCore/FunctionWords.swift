import Foundation

/// Служебные слова русского языка.
///
/// Они не выбрасываются из отбора, а откладываются в последний ярус: до них дело
/// доходит примерно после 55%. Причина в `docs/DECISIONS.md` — они бесполезны
/// для запоминания и самые ошибкоопасные, потому что английский предлог зависит
/// от падежа русского существительного.
public enum FunctionWords {

    /// Проверка по лемме, в нижнем регистре.
    public static func contains(_ lemma: String) -> Bool {
        all.contains(lemma)
    }

    public static let all: Set<String> = prepositions
        .union(conjunctions)
        .union(particles)
        .union(pronouns)
        .union(auxiliaries)

    public static let prepositions: Set<String> = [
        "в", "во", "на", "с", "со", "к", "ко", "от", "до", "из", "изо", "у", "за",
        "по", "о", "об", "обо", "под", "подо", "над", "надо", "при", "про", "для",
        "без", "между", "через", "перед", "передо", "около", "возле", "вокруг",
        "вдоль", "сквозь", "среди", "кроме", "против", "ради", "после", "вместо",
        "мимо", "внутри", "вне", "напротив", "благодаря", "согласно", "вопреки"
    ]

    public static let conjunctions: Set<String> = [
        "и", "а", "но", "да", "или", "либо", "что", "чтобы", "если", "когда", "пока",
        "хотя", "потому", "поэтому", "зато", "также", "тоже", "как", "будто",
        "словно", "чем", "ибо", "затем", "причём", "однако"
    ]

    public static let particles: Set<String> = [
        "не", "ни", "же", "ли", "бы", "вот", "вон", "ведь", "уж", "разве", "неужели",
        "лишь", "только", "даже", "именно", "пусть", "пускай", "то", "-то", "ка"
    ]

    public static let pronouns: Set<String> = [
        "я", "ты", "он", "она", "оно", "они", "мы", "вы",
        "мой", "твой", "его", "её", "их", "наш", "ваш", "свой", "себя",
        "этот", "тот", "такой", "который", "какой", "чей", "весь", "всё", "все",
        "кто", "что", "никто", "ничто", "некто", "нечто", "каждый", "любой",
        "другой", "сам", "самый", "иной", "некоторый"
    ]

    /// Формы местоимений, которые совпадают с существительными.
    ///
    /// `NLTagger` разбирает «о том» как «том» — книжный том, volume. Читатель
    /// видит «и о volume, что скоро наступит осень», и это выглядит поломкой
    /// приложения, а не смелым переводом. Такие формы не переводятся никогда:
    /// проиграть здесь можно только редкое существительное, а выиграть —
    /// частую конструкцию.
    public static let ambiguousPronounForms: Set<String> = [
        "том", "тем", "той", "тому", "тою", "те", "теми",
        "этом", "этим", "этими", "эти",
        "нём", "нем", "ней", "неё", "нему", "ним", "ними", "них",
        "мой", "моей", "три", "стать", "пора"
    ]

    /// Вспомогательные и связочные глаголы. «Был», «стал», «казался» — не то,
    /// ради чего человек ставил приложение.
    public static let auxiliaries: Set<String> = [
        "быть", "стать", "становиться", "являться", "оказаться", "оказываться",
        "казаться", "показаться", "выглядеть",
        "мочь", "смочь", "хотеть", "должен", "нужно", "надо", "можно"
    ]
}

/// Английский предлог для русского.
///
/// Полное решение требует падежа существительного, которым управляет предлог:
/// «с кровати» → *from*, но «с другом» → *with*. Падежа у нас нет — `NLTagger`
/// его не даёт. Поэтому здесь частотный вариант плюс таблица устойчивых сочетаний.
///
/// Это осознанное упрощение, а не недоделка: предлоги переводятся только выше 55%,
/// где качество и так объявлено подстрочником. Усложнять до появления настоящей
/// морфологии не нужно — см. раздел «Открыто» в `docs/DECISIONS.md`.
public enum PrepositionRules {

    /// Частотный английский эквивалент.
    public static let common: [String: String] = [
        "в": "in", "во": "in", "на": "on", "с": "with", "со": "with",
        "к": "to", "ко": "to", "от": "from", "до": "until", "из": "from",
        "у": "at", "за": "behind", "по": "along", "о": "about", "об": "about",
        "под": "under", "над": "above", "при": "at", "про": "about", "для": "for",
        "без": "without", "между": "between", "через": "through", "перед": "before",
        "около": "near", "возле": "near", "вокруг": "around", "вдоль": "along",
        "сквозь": "through", "среди": "among", "кроме": "except", "против": "against",
        "после": "after", "вместо": "instead of", "мимо": "past", "внутри": "inside"
    ]

    /// Устойчивые сочетания «глагол + предлог». Ключ — «леммаГлагола предлог».
    /// Побеждают частотный вариант, если предыдущее знаменательное слово совпало.
    ///
    /// Список пополняется по мере тестирования на реальных книгах. Он не обязан
    /// быть полным — он обязан покрывать частое.
    public static let collocations: [String: String] = [
        "лаять на": "at",
        "смотреть на": "at",
        "глядеть на": "at",
        "кричать на": "at",
        "надеяться на": "for",
        "блестеть от": "with",
        "дрожать от": "with",
        "устать от": "of",
        "встать с": "from",
        "подняться с": "from",
        "упасть с": "off",
        "идти по": "along",
        "ходить по": "around",
        "бежать по": "along",
        "думать о": "about",
        "говорить о": "about",
        "мечтать о": "of",
        "ждать за": "for",
        "идти за": "for"
    ]

    /// Английский предлог с учётом предыдущего глагола, если он известен.
    ///
    /// - Parameters:
    ///   - preposition: лемма предлога, в нижнем регистре
    ///   - governingVerb: лемма ближайшего предшествующего глагола, если есть
    /// - Returns: английский предлог и пояснение для карточки слова
    public static func english(for preposition: String,
                               governingVerb: String?) -> (word: String, note: String)? {
        if let verb = governingVerb,
           let special = collocations["\(verb) \(preposition)"] {
            return (special, "устойчивое сочетание: \(verb) \(preposition) → \(verb) \(special)")
        }
        guard let word = common[preposition] else { return nil }
        return (word, "частотный вариант; точный зависит от падежа")
    }
}
