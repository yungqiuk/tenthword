import Foundation

/// Детерминированный хеш — FNV-1a, 64 бита.
///
/// Стандартный `Hasher` из Swift намеренно рандомизирован между запусками процесса.
/// Если построить на нём отбор слов, план перевода будет разным при каждом открытии
/// книги: читатель вернулся на страницу назад — там переведены другие слова.
/// Поэтому в отборе используется **только** этот хеш.
///
/// FNV-1a выбран за то, что его тривиально повторить в любом языке байт в байт —
/// эталонные тесты генерируются независимой реализацией на Python
/// (`tools/make_golden.py`), и они обязаны совпадать.
public enum StableHash {

    /// FNV-1a по UTF-8 представлению строки.
    public static func fnv1a64(_ string: String) -> UInt64 {
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325
        for byte in string.utf8 {
            hash ^= UInt64(byte)
            hash = hash &* 0x0000_0100_0000_01b3
        }
        return hash
    }

    /// Лавинное перемешивание 64-битного слова — финализатор splitmix64.
    ///
    /// Сам по себе FNV-1a плохо разносит старшие биты, когда ключи различаются
    /// только коротким хвостом. А в отборе ключ устроен именно так: `лемма#порядковый`.
    /// Без этого шага джиттер ложится неравномерно, и переведённые слова
    /// собираются в одном месте страницы вместо того, чтобы разойтись по ней.
    ///
    /// Как и FNV-1a, воспроизводится в любом языке байт в байт — в `tools/make_golden.py`
    /// лежит та же функция на Python.
    static func mix(_ value: UInt64) -> UInt64 {
        var x = value
        x ^= x >> 30
        x = x &* 0xbf58_476d_1ce4_e5b9
        x ^= x >> 27
        x = x &* 0x94d0_49bb_1331_11eb
        x ^= x >> 31
        return x
    }

    /// Хеш, разложенный в полуинтервал [0, 1).
    ///
    /// Берём старшие 53 бита перемешанного значения — ровно столько значащих бит
    /// у `Double`, поэтому результат воспроизводится точно, без потерь округления.
    public static func unitInterval(_ string: String) -> Double {
        Double(mix(fnv1a64(string)) >> 11) * 0x1p-53
    }
}
